"""Deterministic standalone CVXPY and YALMIP exports of the canonical cone model."""
from __future__ import annotations

import json
from collections.abc import Mapping
import numpy as np
from control_lab.diagnostics import ValidationError
from .modeling.canonical import CanonicalSDPProblem


def resolve_problem(problem_or_spec) -> CanonicalSDPProblem:
    if isinstance(problem_or_spec, CanonicalSDPProblem):
        return problem_or_spec
    if not isinstance(problem_or_spec, Mapping):
        raise ValidationError("Expected CanonicalSDPProblem or control template specification.")
    if "blocks" in problem_or_spec and "c" in problem_or_spec:
        return CanonicalSDPProblem.from_dict(problem_or_spec)
    # Share the RPC's canonical/template lowering, including signs and TS hypotheses.
    from control_lab.core.rpc import _resolve_sdp_problem_from_payload
    return _resolve_sdp_problem_from_payload(problem_or_spec, store=None, project_id="offline-export")


def _payload(problem):
    variables = {name: {key: meta[key] for key in ("shape", "symmetric", "offset", "coords")}
                 for name, meta in problem.variable_map.items()}
    return dict(c=problem.c.tolist(), c0=problem.c0,
                blocks=[dict(F0=b.F0.tolist(), Fk=[b.get_Fk(k).tolist() for k in range(problem.n_vars)])
                        for b in problem.blocks],
                E=problem.E.tolist(), d=problem.d.tolist(), H=problem.H.tolist(), h=problem.h.tolist(),
                variables=variables, recovery=problem.recovery_plan)


def export_to_cvxpy_script(problem_or_spec) -> str:
    problem = resolve_problem(problem_or_spec)
    encoded = json.dumps(_payload(problem), sort_keys=True, indent=2, ensure_ascii=True)
    literal = "\n".join("    " + repr(line + "\n") for line in encoded.splitlines())
    return '''# Generated by ControlLab Web, ADR-010. Install numpy and cvxpy.
import json
import numpy as np
import cvxpy as cp

DATA = json.loads(
''' + literal + '''
)
x = cp.Variable(len(DATA['c']), name='x')
constraints = []
for i, block in enumerate(DATA['blocks']):
    affine = np.array(block['F0'], dtype=float)
    for k, coefficient in enumerate(block['Fk']):
        affine = affine + x[k] * np.array(coefficient, dtype=float)
    slack = cp.Variable(affine.shape, PSD=True, name=f'S_{i}')
    constraints.append(slack == affine)
if DATA['d']:
    constraints.append(np.array(DATA['E']) @ x == np.array(DATA['d']))
if DATA['h']:
    constraints.append(np.array(DATA['H']) @ x <= np.array(DATA['h']))
problem = cp.Problem(cp.Minimize(np.array(DATA['c']) @ x + DATA['c0']), constraints)
problem.solve(solver=cp.CLARABEL)
print('status', problem.status, 'objective', problem.value)
if problem.status not in (cp.OPTIMAL, cp.OPTIMAL_INACCURATE):
    raise RuntimeError('No finite primal solution. Inspect solver status and certificates.')
print('constraint violations', [float(np.max(c.violation())) for c in constraints])
variables = {}
for name, meta in DATA['variables'].items():
    matrix = np.zeros(meta['shape'])
    for index, (row, col) in enumerate(meta['coords']):
        matrix[row, col] = x.value[meta['offset'] + index]
        if meta['symmetric']:
            matrix[col, row] = matrix[row, col]
    variables[name] = matrix
plan = DATA['recovery']
if 'Q_var' in plan:
    P = variables[plan['Q_var']]
    if np.linalg.eigvalsh(P).min() <= 0:
        raise RuntimeError('Gain recovery requires positive definite P.')
    gains = {}
    for name in plan.get('Y_vars', [plan.get('Y_var')]):
        M = variables[name]
        K = np.linalg.solve(P.T, M.T).T
        gains[name] = K
    print('feedback_sign', plan['feedback_sign'], 'gains', gains)
print('variables', variables)
# Solver output requires independent primal/dual and closed-loop validation.
'''


def _matlab(matrix) -> str:
    a = np.asarray(matrix, dtype=float)
    if not a.size:
        return f"zeros({a.shape[0]}, {a.shape[1] if a.ndim == 2 else 1})"
    if a.ndim == 1:
        a = a.reshape(-1, 1)
    return "[" + "; ".join(" ".join(format(v, '.17g') for v in row) for row in a) + "]"


def export_to_yalmip_script(problem_or_spec) -> str:
    problem = resolve_problem(problem_or_spec)
    lines = ["% Generated by ControlLab Web, ADR-010. Requires YALMIP and a dedicated SDP solver.",
             "yalmip('clear');", f"x = sdpvar({problem.n_vars},1);", "constraints = [];"]
    for i, block in enumerate(problem.blocks):
        lines.append(f"F{i} = {_matlab(block.F0)};")
        for k, coefficient in block.F_terms.items():
            lines.append(f"F{i} = F{i} + x({k+1}) * {_matlab(coefficient)};")
        lines.append(f"constraints = [constraints, F{i} >= 0];")
    if problem.n_eq:
        lines.append(f"constraints = [constraints, {_matlab(problem.E)} * x == {_matlab(problem.d)}];")
    if problem.n_ineq:
        lines.append(f"constraints = [constraints, {_matlab(problem.H)} * x <= {_matlab(problem.h)}];")
    lines.extend([f"objective = {_matlab(problem.c.reshape(1,-1))} * x + {problem.c0:.17g};",
                  "settings = sdpsettings('solver','sdpt3','verbose',1);",
                  "diagnostics = optimize(constraints, objective, settings);",
                  "disp(diagnostics);", "if diagnostics.problem ~= 0, error('SDP solve failed'); end",
                  "residuals = check(constraints); disp(residuals);",
                  "if min(residuals) < -1e-7, error('Primal residual exceeds tolerance'); end"])
    # Original symbolic coordinates are reconstructed from canonical x, without scaling ambiguity.
    plan = problem.recovery_plan
    if 'Q_var' in plan and plan.get('feedback_sign') not in ('positive', 'negative'):
        raise ValidationError("Gain recovery requires an explicit valid feedback sign.")
    if 'Q_var' in plan:
        names = [plan['Q_var']] + plan.get('Y_vars', [plan.get('Y_var')])
        for index, name in enumerate(names):
            meta = problem.variable_map[name]
            target = 'P' if index == 0 else f'M{index}'
            rows, cols = meta['shape']
            entries = [['0' for _ in range(cols)] for _ in range(rows)]
            for j, (row, col) in enumerate(meta['coords']):
                entries[row][col] = f"x({meta['offset']+j+1})"
                if meta['symmetric']:
                    entries[col][row] = entries[row][col]
            lines.append(f"{target} = [" + "; ".join(" ".join(row) for row in entries) + "];")
        lines.append(f"K = cell(1,{len(names)-1});")
        lines.append("if min(eig(value(P))) <= 0, error('P must be positive definite'); end")
        for index in range(1, len(names)):
            lines.extend([f"M = M{index};", f"K{{{index}}} = value(M) / value(P);", f"disp(K{{{index}}});"])
        lines.append("% Apply the feedback sign recorded by the template.")
        lines.append("feedback_sign = '" + plan['feedback_sign'] + "';")
    lines.extend(["disp(value(x));", "% Independently verify dual residuals and closed-loop dynamics before use."])
    return '\n'.join(lines) + '\n'

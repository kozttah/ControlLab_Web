"""F9 independent FML probes, CL-DIR-001 §§5.6/9.4; analytic y=x.

No expected value is generated by the importer/exporter under test. The two
shoulder triangles form (1-x)/2 and (1+x)/2 on [-1,1], with consequents -1/+1.
"""

import numpy as np
import pytest
import xml.etree.ElementTree as ET

from control_lab.core import FuzzySystem
from control_lab.fuzzy import evaluate, export_fml, import_fml


XML = '''<fuzzySystem name="F9Analytic" profile="IEEE-1855-2016">
  <knowledgeBase>
    <fuzzyVariable name="x" type="input" domainleft="-1" domainright="1">
      <fuzzyTerm name="Low"><triangularShape param1="-1" param2="-1" param3="1"/></fuzzyTerm>
      <fuzzyTerm name="High"><triangularShape param1="-1" param2="1" param3="1"/></fuzzyTerm>
    </fuzzyVariable>
    <tskVariable name="y" type="output" domainleft="-2" domainright="2" defaultvalue="0" combination="WTAVER">
      <tskTerm name="Negative" order="0"><tskValue>-1</tskValue></tskTerm>
      <tskTerm name="Positive" order="0"><tskValue>1</tskValue></tskTerm>
    </tskVariable>
  </knowledgeBase>
  <tskRuleBase name="R" andMethod="PROD" orMethod="MAX">
    <tskRule name="LowRule" connector="and" weight="1">
      <antecedent><clause><variable>x</variable><term>Low</term></clause></antecedent>
      <consequent><clause><variable>y</variable><term>Negative</term></clause></consequent>
    </tskRule>
    <tskRule name="HighRule" connector="and" weight="1">
      <antecedent><clause><variable>x</variable><term>High</term></clause></antecedent>
      <consequent><clause><variable>y</variable><term>Positive</term></clause></consequent>
    </tskRule>
  </tskRuleBase>
</fuzzySystem>'''


def _assert_rejected(xml, **limits):
    result = import_fml(xml, **limits)
    assert result.status == "failure"
    assert result.error is not None and result.error.code
    assert result.data is None
    assert result.provenance.algorithm


@pytest.mark.parametrize("old,new", [
    ('andMethod="PROD"', 'andMethod="UNSUPPORTED"'),
    ('orMethod="MAX"', 'orMethod="UNSUPPORTED"'),
    ('connector="and"', 'connector="xor"'),
    ('defaultvalue="0"', 'defaultvalue="nonnumeric"'),
    ('defaultvalue="0"', 'defaultvalue="NaN"'),
    ('defaultvalue="0"', 'defaultvalue="Infinity"'),
    ('triangularShape param1="-1" param2="-1" param3="1"',
     'triangularShape param1="1" param2="-1" param3="0"'),
    ('triangularShape param1="-1" param2="-1" param3="1"',
     'trapezoidShape param1="-1" param2="1" param3="0" param4="1"'),
    ('triangularShape param1="-1" param2="-1" param3="1"',
     'gaussianShape param1="0" param2="0"'),
    ('triangularShape param1="-1" param2="-1" param3="1"',
     'gaussianShape param1="0" param2="-1"'),
    ('triangularShape param1="-1" param2="-1" param3="1"',
     'bellShape param1="-1" param2="2" param3="0"'),
    ('triangularShape param1="-1" param2="-1" param3="1"',
     'bellShape param1="1" param2="0" param3="0"'),
    ('triangularShape param1="-1" param2="-1" param3="1"',
     'linearShape param1="1" param2="0"'),
    ('tskTerm name="Negative" order="0"', 'tskTerm name="Negative" order="1"'),
])
def test_f9_fml_invalid_semantics_are_not_repaired(old, new):
    _assert_rejected(XML.replace(old, new, 1))


def test_f9_fml_roundtrip_matches_analytic_partition():
    result = import_fml(XML)
    assert result.status == "success" and result.data is not None
    system = FuzzySystem.from_dict(result.data["fuzzy_system"])
    exported = export_fml(system)
    assert exported.status == "success" and exported.data is not None
    imported_again = import_fml(exported.data["fml_xml"])
    assert imported_again.status == "success" and imported_again.data is not None
    restored = FuzzySystem.from_dict(imported_again.data["fuzzy_system"])
    for x in np.linspace(-1.0, 1.0, 21):
        for candidate in (system, restored):
            value = evaluate(candidate, {"x": float(x)})
            assert value.status == "success"
            assert value.data["outputs"]["y"] == pytest.approx(float(x), abs=1e-12)


def test_f9_fml_dtd_and_resource_limits_fail_closed():
    payload = '<!DOCTYPE fuzzySystem [<!ENTITY external SYSTEM "file:///nonexistent/f9-secret">]>' + XML
    _assert_rejected(payload)
    _assert_rejected(XML, max_bytes=20)
    _assert_rejected(XML, max_depth=2)
    _assert_rejected(XML, max_elements=3)


def test_f9_fml_unrepresentable_duplicate_clauses_are_not_collapsed():
    clause = '<clause><variable>x</variable><term>Low</term></clause>'
    # A mapping x->term cannot retain Low AND High as two simultaneous premises.
    duplicate = clause + '<clause><variable>x</variable><term>High</term></clause>'
    _assert_rejected(XML.replace(clause, duplicate, 1))


@pytest.mark.parametrize("bias_last,coefficients", [(True, [2, 0]), (False, [0, 2])])
def test_f9_explicit_first_order_consequents_preserve_y_equals_2x(bias_last, coefficients):
    root = ET.fromstring(XML)
    for term in root.iter("tskTerm"):
        term.set("order", "1")
        term.set("biasLast", str(bias_last).lower())
        for child in list(term):
            term.remove(child)
        for coefficient in coefficients:
            ET.SubElement(term, "tskValue").text = str(coefficient)
    imported = import_fml(ET.tostring(root, encoding="unicode"))
    assert imported.status == "success"
    original = FuzzySystem.from_dict(imported.data["fuzzy_system"])
    exported = export_fml(original)
    assert exported.status == "success"
    repeated = import_fml(exported.data["fml_xml"])
    assert repeated.status == "success"
    restored = FuzzySystem.from_dict(repeated.data["fuzzy_system"])
    for x in np.linspace(-1.0, 1.0, 9):
        for system in (original, restored):
            value = evaluate(system, {"x": float(x)})
            assert value.status == "success"
            assert value.data["output"] == pytest.approx(2 * float(x), abs=1e-12)
